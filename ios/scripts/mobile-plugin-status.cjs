// Writes docs/MOBILE-PLUGINS.md: every desktop plugin and whether it runs on CloudCord mobile.
// Run from the repo root: node ios/scripts/mobile-plugin-status.cjs
const fs = require('node:fs');
const path = require('node:path');

const desktop = 'desktop/client/src';
const mobile = 'ios/runtime/src/core/plugins';
const ported = new Set(fs.readdirSync(mobile).map(name => name.toLowerCase()));
// Desktop plugins whose mobile version has a different id.
const aliases = { readallnotificationsbutton: 'readallnotifications', messageloggerenhanced: 'messagelogger', messagelogger: 'messagelogger', musicrichpresence: 'lastfmrichpresence' };
// Features CloudCord mobile already has built in.
const builtIn = { fakeprofile: 'Custom Profile editor', notrack: 'NoTrack core plugin', platformspoofer: 'mobile platform is native', userplugininstaller: 'mobile plugin installer', themelibrary: 'Themes tab', fontloader: 'Fonts tab' };

// Things a phone app can't do at all.
const DESKTOP_ONLY = /\.(desktop|discordDesktop|web|dev|sinbop)$|arRPC|krisp|xsOverlay|orbolay|steam|appleMusic|screenshare|screenRecorder|devtools|consoleJanitor|consoleShortcuts|f8break|webpackTarball|elementHighlighter|keyboardNavigation|keybind|quickThemeSwitcher|noSystemBadge|noRPC|title$|idleAutoRestart|cursorBuddy|noF1|noMiddleClickPaste|middleClickTweaks|recentDMSwitcher|quickReply|crashHandler|reactErrorDecoder|startupTimings|webContextMenus|streamingCodec|limitlessScreenshare|instantScreenshare|clipUpload|clipsEnhancements|micLoopback|noDeepLinks|unlockedAvatarZoom|imageZoom|pictureInPicture|devCompanion|iconViewer/i;

const rows = [];
for (const group of ['plugins', 'sincordplugins']) {
    for (const name of fs.readdirSync(path.join(desktop, group)).sort((a, b) => a.localeCompare(b))) {
        if (name.startsWith('_')) continue;
        const dir = path.join(desktop, group, name);
        const file = ['index.ts', 'index.tsx'].map(f => path.join(dir, f)).find(fs.existsSync);
        if (!file) continue;
        const source = fs.readFileSync(file, 'utf8');
        const description = (source.match(/definePlugin\(\{[\s\S]*?\n    description: "([^"]*)"/) || [, ''])[1];
        const key = name.toLowerCase().replace(/\..*$/, '');
        let status, note = '';
        if (ported.has(key) || ported.has(aliases[key])) { status = 'On mobile'; note = aliases[key] && aliases[key] !== key ? `as ${aliases[key]}` : ''; }
        else if (builtIn[key]) { status = 'Built in'; note = builtIn[key]; }
        else if (/fakeNitro|noNitroUpsell|noPushToTalk|questify|spotifyCrack/i.test(name)) { status = 'Not planned'; note = 'not offered on CloudCord mobile'; }
        else if (DESKTOP_ONLY.test(name)) { status = 'Desktop only'; note = 'needs desktop, browser or PC hardware features'; }
        else { status = 'Needs mobile UI'; note = "patches desktop screens; needs rebuilding against the phone app's components and testing on a device"; }
        rows.push({ name, description, status, note });
    }
}

const order = ['On mobile', 'Built in', 'Needs mobile UI', 'Desktop only', 'Not planned'];
const counts = Object.fromEntries(order.map(s => [s, rows.filter(r => r.status === s).length]));
const lines = [
    '# Desktop plugins on CloudCord mobile',
    '',
    `Generated by \`ios/scripts/mobile-plugin-status.cjs\`. ${rows.length} desktop plugins:`,
    '',
    ...order.map(s => `- **${s}:** ${counts[s]}`),
    '',
    'Mobile versions are rewrites that credit each plugin\'s original authors, and are off until turned on under Plugins.',
    '',
    ...order.flatMap(status => [
        `## ${status} (${counts[status]})`,
        '',
        '| Plugin | What it does | Note |',
        '| --- | --- | --- |',
        ...rows.filter(r => r.status === status).map(r => `| ${r.name} | ${r.description.replace(/\|/g, '\\|')} | ${r.note} |`),
        '',
    ]),
];
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/MOBILE-PLUGINS.md', lines.join('\n'));
console.log(order.map(s => `${s}: ${counts[s]}`).join(' | '));
