const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const esbuild = require('esbuild');
const source = fs.readFileSync('src/sincordplugins/fakeProfile/index.tsx', 'utf8');
const dateFunction = source.match(/function shortProfileDate\(date: Date\): string \{[\s\S]*?\n\}/)[0];
const dates = vm.createContext({ Date });
vm.runInContext(esbuild.transformSync(dateFunction, { loader: 'ts' }).code, dates);
assert.equal(dates.shortProfileDate(new Date(2024, 0, 6)), '1/6/24');
assert.equal(dates.shortProfileDate(new Date(2026, 10, 14)), '11/14/26');
const start = source.indexOf('const textRewriter = new class');
const end = source.indexOf('const startDomObserver', start);
const context = vm.createContext({ isEnabled: true, _realUsername: 'realuser', _realGlobalName: '', storedData: { username: 'customuser' } });
vm.runInContext(esbuild.transformSync(source.slice(start, end) + '\nglobalThis.rewriter = textRewriter;', { loader: 'ts' }).code, context);
for (const editor of ['contenteditable', 'textbox', 'textarea', 'input']) {
    const text = { nodeValue: 'realuser', parentElement: { closest: () => ({ editor }) } };
    context.rewriter.rewrite(text);
    assert.equal(text.nodeValue, 'realuser', editor + ' must remain owned by Discord');
    text.nodeValue = 'realuse';
    context.rewriter.rewrite(text);
    assert.equal(text.nodeValue, 'realuse', 'backspace must not restore cached editor text');
}
const label = { nodeValue: 'realuser', parentElement: { closest: () => null } };
context.rewriter.rewrite(label);
assert.equal(label.nodeValue, 'customuser', 'visible profile labels still get rewritten');
label.nodeValue = 'another person';
context.rewriter.rewrite(label);
assert.equal(label.nodeValue, 'another person', 'reused Discord text nodes must not restore the previous profile');
label.nodeValue = 'realuser updated';
context.rewriter.rewrite(label);
assert.equal(label.nodeValue, 'customuser updated', 'new native text becomes the replacement source');
context.storedData.username = 'newcustom';
context.rewriter.rewrite(label);
assert.equal(label.nodeValue, 'newcustom updated', 'editing the custom name uses the latest native text');
context.storedData.username = '';
context.rewriter.rewrite(label);
assert.equal(label.nodeValue, 'realuser updated', 'removing the override restores the current native text');
context.storedData.username = 'customuser';
context.rewriter.rewrite(label);
context.document = { body: {}, createTreeWalker: () => { let done = false; return { nextNode: () => done ? null : (done = true, label) }; } };
context.NodeFilter = { SHOW_TEXT: 4 };
context.rewriter.stop();
assert.equal(label.nodeValue, 'realuser updated', 'cleanup restores text still owned by CloudCord');
context.rewriter.rewrite(label);
label.nodeValue = 'native update before stopping';
context.rewriter.stop();
assert.equal(label.nodeValue, 'native update before stopping', 'cleanup must preserve a newer native update');
const timers = new Map(), frames = new Map();
let nextTask = 0, notify;
context.setTimeout = callback => { timers.set(++nextTask, callback); return nextTask; };
context.clearTimeout = id => timers.delete(id);
context.requestAnimationFrame = callback => { frames.set(++nextTask, callback); return nextTask; };
context.cancelAnimationFrame = id => frames.delete(id);
context.Node = { TEXT_NODE: 3 };
context.MutationObserver = class { constructor(callback) { notify = callback; } observe() {} disconnect() {} };
context.rewriter.start();
notify([{ type: 'characterData', target: label }]);
context.rewriter.stop();
assert.equal(timers.size, 0, 'stopping cancels queued text rewrite timers');
assert.equal(context.rewriter.pending.length, 0, 'stopping releases queued mutation records');
context.rewriter.start();
notify([{ type: 'characterData', target: label }]);
assert.equal(timers.size, 1, 'restarting can schedule a fresh rewrite');
for (const [id, callback] of timers) { timers.delete(id); callback(); }
assert.equal(frames.size, 1);
context.rewriter.stop();
assert.equal(frames.size, 0, 'stopping cancels pending animation frames too');
console.log('PASS editable text, reused native labels, custom name updates and non-destructive cleanup');
