const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict'), esbuild = require('esbuild');
const source = fs.readFileSync('src/sincordplugins/fakeProfile/extras.tsx', 'utf8');
const user = { id: 'me', username: 'User' }, role = { id: 'local-role', hoist: true, position: 100, name: 'Local' };
let enabled = true, joined = true, member = null;
const stores = { GuildMemberStore: { getMember: () => member, getSelfMember: () => null }, UserStore: { getCurrentUser: () => user, getUser: () => user },
    GuildStore: { getGuild: () => joined ? { id: 'guild' } : null }, PresenceStore: { getStatus: () => 'online', getActivities: () => [] } };
const ctx = vm.createContext({ ...stores, boostFor: () => enabled ? { roles: [role.id] } : null, rolesOf: () => [role], fakeMember: (_guild, row) => row });
const code = source.slice(source.indexOf('const listCache ='), source.indexOf('// Visual ownership:'));
vm.runInContext(esbuild.transformSync(code, { loader: 'ts' }).code, ctx);
const original = { rows: [{ type: 'GROUP', id: 'online' }, { type: 'MEMBER', userId: 'other' }], groups: [{ id: 'online', count: 2 }] };
const result = ctx.regroupMemberList('guild', original);
assert.notEqual(result, original);
assert.equal(result.rows.filter(row => row.userId === 'me').length, 1, 'an unloaded own row is reconstructed');
assert.equal(result.rows[0].id, role.id);
assert.equal(result.rows[1].userId, 'me');
assert.equal(result.groups.find(group => group.id === 'online').count, 1);
assert.equal(original.rows.length, 2, 'native rows remain untouched');
assert.equal(ctx.regroupMemberList('guild', original), result, 'repeat reads do not destabilize the member list');
joined = false;
const unavailable = { ...original }; assert.equal(ctx.regroupMemberList('guild', unavailable), unavailable);
joined = true; enabled = false; assert.equal(ctx.regroupMemberList('guild', original), original);
const workflow = fs.readFileSync('../../.github/workflows/cloudcord.yml', 'utf8');
const start = workflow.indexOf('          function selfMemberRow(');
const mobile = workflow.slice(start, workflow.indexOf('          // ---- Visual roles:', start)).replace(/^          /gm, '');
const phone = vm.createContext({ findByStoreName: name => stores[name] });
vm.runInContext(esbuild.transformSync(mobile, { loader: 'ts' }).code, phone);
assert.equal(phone.selfMemberRow('guild', 'me').userId, 'me');
joined = false; assert.equal(phone.selfMemberRow('guild', 'me'), null);
console.log('PASS desktop/mobile unloaded self rows, local role grouping, native immutability and stable snapshots');
