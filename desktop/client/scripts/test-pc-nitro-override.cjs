const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const esbuild = require('esbuild');
const source = fs.readFileSync('src/sincordplugins/fakeProfile/extras.tsx', 'utf8');
let owner = 'account-a', emits = 0;
let state = { premiumTypeActual: 0, premiumTypeOverride: 2 };
const ctx = vm.createContext({ extras: { fakeNitro: false }, UserStore: { getCurrentUser: () => ({ id: owner }) },
    OverridePremiumTypeStore: { getState: () => state, emitChange: () => emits++ } });
const helper = source.slice(source.indexOf('let ownedNitroOverride:'), source.indexOf('// ---- Fake gift link'));
vm.runInContext(esbuild.transformSync(helper, { loader: 'ts' }).code, ctx);
ctx.applyFakeNitro();
assert.equal(state.premiumTypeOverride, 2, 'an off switch cannot erase an unrelated existing override');
assert.equal(emits, 0);
state.premiumTypeOverride = 1; ctx.extras.fakeNitro = true;
ctx.applyFakeNitro(); assert.equal(state.premiumTypeOverride, 2);
ctx.applyFakeNitro(); assert.equal(emits, 1, 'unchanged Nitro state must not create rerender loops');
ctx.extras.fakeNitro = false; ctx.applyFakeNitro();
assert.equal(state.premiumTypeOverride, 1, 'turning off restores the override that existed before CloudCord');
state = { premiumTypeActual: 2, premiumTypeOverride: undefined }; ctx.extras.fakeNitro = true;
ctx.applyFakeNitro(); assert.equal(state.premiumTypeOverride, undefined, 'real full Nitro is not overridden');
state = { premiumTypeActual: 0, premiumTypeOverride: undefined };
ctx.applyFakeNitro(); assert.equal(state.premiumTypeOverride, 2);
state.premiumTypeActual = 2;
ctx.applyFakeNitro(); assert.equal(state.premiumTypeOverride, undefined, 'purchasing real Nitro removes the now-unnecessary cosmetic override');
state = { premiumTypeActual: 0, premiumTypeOverride: 1 }; ctx.applyFakeNitro();
owner = 'account-b'; ctx.applyFakeNitro();
ctx.extras.fakeNitro = false; ctx.applyFakeNitro();
assert.equal(state.premiumTypeOverride, undefined, 'switching accounts never restores the previous account override into the new account');
owner = 'account-a'; ctx.extras.fakeNitro = true; ctx.applyFakeNitro();
state.premiumTypeOverride = 1; ctx.extras.fakeNitro = false; ctx.applyFakeNitro();
assert.equal(state.premiumTypeOverride, 1, 'later changes made outside CloudCord are not overwritten during cleanup');
let calls = 0;
const originalPost = function () { assert.equal(this, rest); calls++; return 'native'; };
const rest = { get: () => 'native-get', post: originalPost };
const gift = vm.createContext({ RestAPI: rest, extras: { giftCode: 'preview' }, showToast() {}, Toasts: { Type: {} } });
vm.runInContext(esbuild.transformSync(source.slice(source.indexOf('const giftPath ='), source.indexOf('// Called from the patched gift resolver')), { loader: 'ts' }).code, gift);
gift.installGiftHook();
const stale = rest.post;
assert.equal(rest.post({ url: '/channels/123/messages' }), 'native');
const externalGet = () => 'external-get';
const externalPost = function (...args) { return stale.apply(this, args); };
rest.get = externalGet; rest.post = externalPost;
gift.uninstallGiftHook();
assert.equal(rest.get, externalGet, 'gift cleanup never changes GET');
assert.equal(rest.post, externalPost, 'gift cleanup preserves a later POST wrapper');
assert.equal(rest.post({ url: '/entitlements/gift-codes/preview/redeem' }), 'native', 'retained old gift wrappers become inert on stop');
gift.installGiftHook(); gift.uninstallGiftHook();
assert.equal(rest.post, externalPost, 'restarts restore precisely the previous POST chain');
assert.equal(calls, 2);
console.log('PASS PC Fake Nitro ownership, real subscription preservation, toggle restoration, account isolation, no-op refresh suppression and reversible gift request hooks');
