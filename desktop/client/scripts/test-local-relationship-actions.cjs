const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = { module: { exports: {} } };
vm.runInNewContext(require('esbuild').transformSync(fs.readFileSync('src/utils/localRelationshipActions.ts', 'utf8'), { loader: 'ts', format: 'cjs' }).code, context);
const install = context.module.exports.installLocalRelationshipActions;
(async () => {
    const id = '123456789012345678', ids = new Set([id]);
    let calls = 0, removed = 0;
    const rest = { put: async function () { assert.equal(this, rest); calls++; }, del: async function () { assert.equal(this, rest); calls++; } };
    const originals = { ...rest };
    const hook = install(rest, value => ids.has(value), value => { removed++; ids.delete(value); });
    assert.equal(hook.ready, true);
    await assert.rejects(rest.put({ url: `/users/@me/relationships/${id}` }), /device-only/);
    assert.equal(calls, 0);
    await rest.put({ url: '/users/@me/relationships/999999999999999999' });
    await rest.del({ url: `/users/@me/guilds/${id}` });
    assert.equal(calls, 2);
    assert.equal((await rest.del({ url: `/users/@me/relationships/${id}?location=Friends` })).status, 204);
    assert.equal(removed, 1);
    assert.equal(calls, 2);
    const wrapper = rest.put;
    rest.put = function (...args) { return wrapper.apply(this, args); };
    const external = rest.put;
    hook.stop();
    assert.equal(rest.put, external, 'preserve later wrappers');
    assert.equal(rest.del, originals.del);
    ids.add(id);
    await rest.put({ url: `/users/@me/relationships/${id}` });
    assert.equal(calls, 3, 'retained wrapper becomes inert after stop');
    const frozen = Object.freeze({ ...originals });
    assert.equal(install(frozen, () => true, () => {}).ready, false);
    const partial = { put: originals.put };
    assert.equal(install(partial, () => true, () => {}).ready, false);
    assert.equal(partial.put, originals.put, 'roll back partially installed protection');
    console.log('Local relationship actions: passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
