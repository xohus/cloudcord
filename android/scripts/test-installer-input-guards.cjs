const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = 'android/app/src/main/java/dev/beefers/vendetta/manager/';
const read = path => fs.readFileSync(root + path, 'utf8');
const download = read('installer/step/download/base/DownloadStep.kt');
assert.ok(download.includes('ApkValidation.validate(destination)'));
assert.ok(download.indexOf('verify()', download.indexOf('if (destination.exists())')) < download.indexOf('cached = true'));
assert.ok(download.includes('Discarding invalid cached APK'));
assert.match(download, /catch \(t: Throwable\) \{\s+destination.delete\(\)/);
const input = read('installer/util/ApkValidation.kt');
assert.ok(input.includes('ZipFile(apk).use'));
assert.ok(input.includes('zip.getEntry("AndroidManifest.xml")'));
assert.ok(input.includes('crc.value == entry.crc'));
const runner = read('installer/step/StepRunner.kt');
assert.ok(runner.includes('ApkValidation.validate(source)'));
assert.ok(runner.includes('ApkValidation.validate(out)'));
assert.ok(runner.includes('mutableDiscordApks.add(0, bases.single())'));
assert.ok(runner.includes('ZipFile(source).use'));
assert.ok(read('domain/manager/DownloadManager.kt').includes('bytesDownloaded == totalBytes'));
const resources = read('installer/util/ArscUtil.kt');
assert.ok(resources.includes('Cyclic icon resource reference'));
assert.ok(resources.includes('BinaryResourceValue.Type.REFERENCE'));
assert.ok(resources.includes('visited.toMutableSet()'));
const signer = read('installer/util/Signer.kt');
assert.ok(signer.includes('if (!ks.exists()) migrate(cacheDir, filesDir)'));
assert.ok(signer.includes('overwrite = false'));
assert.ok(signer.includes('atomic.finishWrite(stream)'));
assert.ok(signer.includes('SHA256withRSA'));
assert.ok(signer.includes('require(result.isVerified)'));
const install = read('installer/step/installing/InstallStep.kt');
assert.ok(install.indexOf('Signer.verifyApk(apk)') < install.indexOf('installer.installApks'));
const viewModel = read('ui/viewmodel/installer/InstallerViewModel.kt');
assert.equal((viewModel.match(/job\?\.cancelAndJoin\(\)/g) || []).length, 2);
assert.ok(viewModel.includes('activeRunner.runAll()'));
assert.ok(read('installer/step/Step.kt').includes('if (t is CancellationException) throw t'));
console.log('PASS: installer input and resource source guards (not compilation or device verification)');
